import assert from 'node:assert/strict';
import {personalTarget,ulComparable,biomarkerEffects,latestBiomarkers,DIET_TARGET_RULES} from '../public/bio-calculator/personal-model.js';
import {clinicalEstimate} from '../public/bio-calculator/clinical-absorption.js';
const t=(k,s)=>personalTarget(k,{rda:8,ul:45,optimalMin:8,optimalMax:8},s);
assert.equal(t('iron',{sex:'female',age:30}).rda,18);
assert.equal(t('iron',{sex:'female',age:55}).rda,8);
assert.equal(t('iron',{sex:'male',age:30}).rda,8);
assert.equal(personalTarget('zinc',{rda:11},{sex:'female',age:30}).rda,8);
assert.equal(personalTarget('calcium',{rda:1000,ul:2500},{sex:'female',age:60}).rda,1200);
assert.equal(personalTarget('calcium',{rda:1000,ul:2500},{sex:'female',age:60}).ul,2000);
assert.equal(DIET_TARGET_RULES.vegan.iron[0],1.8);
assert.equal(ulComparable('magnesium',{total:500,supplement:100}),100);
const fx=biomarkerEffects(latestBiomarkers([{marker:'Ferritin',value:10,unit:'µg/L',date:'2026-01-01'}]));
assert.ok(fx.iron.nonHeme>1.9&&fx.iron.nonHeme<2.1);
assert.equal(latestBiomarkers([{marker:'Vitamin D',value:8,unit:'ng/mL',date:'2026-01-01'}]).vitamin_d.value.toFixed(1),'20.0');
const meal={fat:10,nutrients:{iron:{total:10}},antinutrients:{}},v={total:10,plant:10,animal:0,supplement:0};
const lo=clinicalEstimate('iron',v,meal,{biomarkerFx:biomarkerEffects({ferritin:{value:150}})}),hi=clinicalEstimate('iron',v,meal,{biomarkerFx:biomarkerEffects({ferritin:{value:10}})});
assert.ok(hi.max>lo.max*2);
const act=clinicalEstimate('zinc',{total:10,plant:10},meal,{conditions:[{id:'celiac_disease',state:'active_untreated'}]}),trt=clinicalEstimate('zinc',{total:10,plant:10},meal,{conditions:[{id:'celiac_disease',state:'treated_adherent'}]});
assert.ok(act.max<trt.max);
const b=clinicalEstimate('vitamin_b12',{total:5,animal:5},{nutrients:{}},{conditions:[{id:'gastrectomy',state:'total'}]});
assert.ok(Math.abs(b.max-0.05)<1e-9);
assert.ok(lo.maxAbsorbed>=lo.max);
console.log('personal model checks passed');
